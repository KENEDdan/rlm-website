"""Decision 7: printable reports carry every required element, are permission-gated and audit-logged."""

from __future__ import annotations

from pathlib import Path

import pytest
from django.conf import settings
from django.utils.html import escape

from accounts.roles import (
    DEVELOPMENT,
    DISCIPLESHIP,
    EXECUTIVE,
    FINANCE,
    LOGISTICS,
    MEDIA,
    MEMBERSHIP,
    MISSIONS,
)
from audit.models import AuditLog
from finance.models import Donor
from membership.models import Member
from portal.models import Department, DepartmentReport

pytestmark = pytest.mark.django_db
P = "/" + settings.PORTAL_URL
ROLES = {
    "membership": MEMBERSHIP,
    "finance": FINANCE,
    "logistics": LOGISTICS,
    "media": MEDIA,
    "missions": MISSIONS,
    "discipleship": DISCIPLESHIP,
    "development": DEVELOPMENT,
}
REQUIRED = [
    "Rebuilding Lives Ministry",  # ministry name next to the logo
    "logo",
    "Department",
    "Branch",
    "All branches",
    "Period",
    "Financial year",
    "Generated",
    "Generated by",
    "Prepared by",
    "Reviewed by",
    "Approved by",
    "Signature",
    "Print / Save as PDF",
]


def _check(html: str, title: str, *, confidential: bool) -> None:
    assert title in html
    for element in REQUIRED:
        assert element in html, element
    assert ("CONFIDENTIAL" in html) is confidential
    assert "portal-sidebar" not in html and "portal-nav" not in html  # standalone: no portal chrome


@pytest.mark.parametrize("code", list(ROLES))
def test_every_department_dashboard_prints(make_staff, verified_client, code) -> None:  # type: ignore[no-untyped-def]
    user = make_staff(ROLES[code], heads={code})
    resp = verified_client(user).get(P + f"{code}/print/")
    assert resp.status_code == 200
    html = resp.content.decode()
    _check(html, "dashboard report", confidential=code in ("finance", "membership", "discipleship"))
    assert "Test Staff" in html and escape(Department.objects.get(code=code).name) in html
    assert AuditLog.objects.filter(action=AuditLog.Action.PRINT, extra__dashboard=code).exists()


def test_sensitive_dashboard_print_needs_the_head(make_staff, verified_client) -> None:  # type: ignore[no-untyped-def]
    assert verified_client(make_staff(FINANCE)).get(P + "finance/print/").status_code == 403
    assert verified_client(make_staff(MEDIA)).get(P + "media/print/").status_code == 200
    assert verified_client(make_staff(MEDIA)).get(P + "finance/print/").status_code == 403


def test_executive_prints(make_staff, verified_client) -> None:  # type: ignore[no-untyped-def]
    client = verified_client(make_staff(EXECUTIVE))
    _check(client.get(P + "executive/print/").content.decode(), "Executive overview", confidential=False)
    Donor.objects.create(name="SECRET-DONOR")
    html = client.get(P + "executive/finance/print/").content.decode()
    _check(html, "Executive finance summary", confidential=True)
    assert "SECRET-DONOR" not in html
    assert verified_client(make_staff(MEDIA)).get(P + "executive/print/").status_code == 403
    assert verified_client(make_staff(MEDIA)).get(P + "executive/finance/print/").status_code == 403


def test_targets_and_department_report_print(make_staff, verified_client) -> None:  # type: ignore[no-untyped-def]
    founder = verified_client(make_staff(superuser=True))
    _check(founder.get(P + "targets/print/").content.decode(), "Performance targets", confidential=False)
    head_user = make_staff(MEDIA, heads={"media"})
    head = verified_client(head_user)
    head.post(P + "media/reports/generate/", {"month": "2026-10", "period": "monthly"})
    report = DepartmentReport.objects.get()
    html = head.get(P + f"media/reports/{report.pk}/print/").content.decode()
    _check(html, "monthly report", confidential=False)
    assert html.count("Test Staff") >= 2 and "October 2026" in html  # generated by + prepared by
    assert (
        verified_client(make_staff(FINANCE)).get(P + f"media/reports/{report.pk}/print/").status_code == 403
    )


def test_member_list_print_is_gated_like_export(make_staff, verified_client) -> None:  # type: ignore[no-untyped-def]
    Member.objects.create(full_name="Grace Akello", status="active")
    member = verified_client(make_staff(MEMBERSHIP))
    assert (
        member.get(P + "membership/members/print/").status_code == 403
    )  # members cannot export, so cannot print
    head = verified_client(make_staff(MEMBERSHIP, heads={"membership"}))
    html = head.get(P + "membership/members/print/").content.decode()
    _check(html, "Member register", confidential=True)
    assert "Grace Akello" in html
    log = AuditLog.objects.get(action=AuditLog.Action.PRINT, extra__list="members")
    assert log.extra["rows"] == 1 and "Grace" not in str(log.extra)
    assert b"membership/members/print/" in head.get(P + "membership/members/").content  # button on the list
    assert b"membership/members/print/" not in member.get(P + "membership/members/").content


def test_volunteer_and_procurement_lists_print(make_staff, verified_client) -> None:  # type: ignore[no-untyped-def]
    fin_head = verified_client(make_staff(FINANCE, heads={"finance"}))
    _check(fin_head.get(P + "finance/volunteers/print/").content.decode(), "volunteer", confidential=True)
    log_head = verified_client(make_staff(LOGISTICS, heads={"logistics"}))
    assert log_head.get(P + "logistics/orders/print/").status_code == 200


def test_buttons_on_screens(make_staff, verified_client) -> None:  # type: ignore[no-untyped-def]
    founder = verified_client(make_staff(superuser=True))
    assert b"/print/" in founder.get(P + "membership/").content
    assert b"executive/print/" in founder.get(P + "executive/").content
    assert b"executive/finance/print/" in founder.get(P + "executive/finance/").content
    assert b"targets/print/" in founder.get(P + "targets/").content


def test_print_stylesheet_rules() -> None:
    css = (Path(settings.BASE_DIR) / "static" / "css" / "input.css").read_text(encoding="utf-8")
    for rule in (
        "size: A4",
        "counter(page)",
        "display: table-header-group",
        "break-inside: avoid",
        "print-color-adjust",
        ".print-toolbar",
    ):
        assert rule in css, rule
