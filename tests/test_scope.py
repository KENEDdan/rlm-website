def test_super_admin_sets_scope_per_assignment(make_staff, verified_client, branches, rf) -> None:  # type: ignore[no-untyped-def]
    juba, _ = branches
    from accounts import reauth

    founder = make_staff(superuser=True)
    target = make_staff(email="t@example.test")
    request = rf.post("/")
    request.user, request.session = founder, {}
    reauth.mark_fresh(request)
    spec = services.RoleSpec(
        departments={"membership": (False, juba.pk), "logistics": (True, None)},
        extra_roles={BRANCH_COORDINATOR},
        branch_id=juba.pk,
    )
    services.change_roles(request, target, spec)
    roles = {m.department.code: (m.is_head, m.branch_id) for m in target.memberships.all()}
    assert roles == {"membership": (False, juba.pk), "logistics": (True, None)}
    assert services.current_spec(target).departments == roles
