def test_multi_department_user_has_a_scope_per_assignment(make_staff, verified_client, branches, people) -> None:  # type: ignore[no-untyped-def]
    juba, yei = branches
    InventoryItem.objects.create(name="Yei chairs", branch=yei)
    InventoryItem.objects.create(name="Juba chairs", branch=juba)
    user = make_staff(MEMBERSHIP, LOGISTICS, BRANCH_COORDINATOR, branch=juba, scoped={"membership": juba})
    access = Access(user)
    assert access.branch_scope("membership") == (True, juba.pk)
    assert access.branch_scope("logistics") == (False, None)
    client = verified_client(user)
    assert "Yei Member" not in _names(client.get(P + "membership/members/"))
    inventory = _names(client.get(P + "logistics/inventory/"))
    assert "Yei chairs" in inventory and "Juba chairs" in inventory
    # nothing from departments the user has no role in
    assert client.get(P + "finance/ledger/").status_code == 403


def test_single_branch_finance_scope_on_ledger_budget_and_dashboard(make_staff, verified_client, branches) -> None:  # type: ignore[no-untyped-def]
    juba, yei = branches
    year = timezone.localdate().year
    dept = Department.objects.get(code="missions")
    BudgetLine.objects.create(
        year=year, department=dept, branch=juba, category="travel", name="Juba travel", amount=100
    )
    BudgetLine.objects.create(
        year=year, department=dept, branch=yei, category="travel", name="Yei travel", amount=900
    )
    for branch, amount in ((juba, 10), (yei, 500), (None, 70)):
        LedgerEntry.objects.create(
            kind="income",
            income_source="offering",
            amount=Decimal(amount),
            description=f"gift {amount}",
            branch=branch,
            status="posted",
            number=f"IN-T-{amount}",
        )
    client = verified_client(make_staff(FINANCE, heads={"finance"}, scoped={"finance": juba}))
    ledger = _names(client.get(P + "finance/ledger/"))
    assert "gift 10" in ledger and "gift 500" not in ledger and "gift 70" not in ledger
    budget = _names(client.get(P + "finance/budget/"))
    assert "Juba travel" in budget and "Yei travel" not in budget
    kpis = {k.code: k.value for k in client.get(P + "finance/").context["board"].kpis}
    assert kpis["cash_position"] == "10.00"


