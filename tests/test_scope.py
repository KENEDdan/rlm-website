P = "/" + settings.PORTAL_URL


@pytest.fixture
def branches():  # type: ignore[no-untyped-def]
    return Branch.objects.get(slug="juba"), Branch.objects.get(slug="yei")


@pytest.fixture
def people(branches):  # type: ignore[no-untyped-def]
    juba, yei = branches
    return {
        "juba": Member.objects.create(
            full_name="Juba Member", status="active", branch=juba, member_number="J1"
        ),
        "yei": Member.objects.create(full_name="Yei Member", status="active", branch=yei),
        "none": Member.objects.create(full_name="No Branch Member", status="active"),
    }


def _names(resp) -> str:  # type: ignore[no-untyped-def]
    return resp.content.decode()


def test_coordinator_only_sees_own_branch_in_three_departments(make_staff, verified_client, branches, people) -> None:  # type: ignore[no-untyped-def]
    juba, _ = branches
    client = verified_client(make_staff(BRANCH_COORDINATOR, branch=juba))
    page = _names(client.get(P + "membership/members/"))
    assert "Juba Member" in page and "Yei Member" not in page and "No Branch Member" not in page
    assert client.get(P + f"membership/members/{people['yei'].pk}/").status_code == 404
    assert client.get(P + "logistics/").status_code == 403 and client.get(P + "finance/").status_code == 403


def test_coordinator_serving_in_a_department_is_limited_to_that_branch(make_staff, verified_client, branches, people) -> None:  # type: ignore[no-untyped-def]
    juba, yei = branches
    user = make_staff(
        MEMBERSHIP, BRANCH_COORDINATOR, branch=juba, heads={"membership"}, scoped={"membership": juba}
    )
    client = verified_client(user)
    page = _names(client.get(P + "membership/members/"))
    assert "Juba Member" in page and "Yei Member" not in page and "No Branch Member" not in page
    # guessing IDs from another branch
    for pk in (people["yei"].pk, people["none"].pk):
        assert client.get(P + f"membership/members/{pk}/").status_code == 404
        assert client.get(P + f"membership/members/{pk}/edit/").status_code == 404
        assert client.post(P + f"membership/members/{pk}/delete/").status_code == 404
    # export and search respect scope
    csv = b"".join(client.get(P + "membership/members/export.csv").streaming_content).decode()
    assert "Juba Member" in csv and "Yei Member" not in csv
    assert "Juba Member" not in _names(client.get(P + "membership/members/?q=nothing"))
    # dashboard figures and charts count only Juba
    kpis = {k.code: k.value for k in client.get(P + "membership/").context["board"].kpis}
    assert kpis["active_members"] == 1
    # cannot create a record in another branch; a record with no branch gets theirs
    client.post(P + "membership/members/new/", {"full_name": "Sneaky", "branch": yei.pk})
    assert Member.objects.count() == 3
    client.post(P + "membership/members/new/", {"full_name": "Filled in"})
    assert Member.objects.order_by("-pk").first().branch == juba
    # reports generated by a single-branch head contain only their branch's figures
    client.post(P + "membership/reports/generate/", {"month": timezone.localdate().strftime("%Y-%m")})
    figures = {f["code"]: f["value"] for f in DepartmentReport.objects.get().figures}
    assert figures["active_members"] == "1"  # only the Juba member (the new record is not active yet)


